def land_cells(cols, rows):
    """(land hexes, lake hexes) on the grid, from the coastline polygons."""
    polys = [EUROPE_ASIA, SCANDINAVIA, BRITAIN, IRELAND, AFRICA, NORTH_AMERICA, SOUTH_AMERICA] + ISLANDS
    boxes = [(bbox(p), p) for p in polys]
    seas = [(bbox(p), p) for p in SEAS]
    lakes_ = [(bbox(p), p) for p in LAKES]

    def hit(point, shapes):
        return any(b[0] <= point[0] <= b[2] and b[1] <= point[1] <= b[3] and inside(point, p) for b, p in shapes)

    land, lakes = set(), set()
    for r in range(rows):
        for c in range(cols):
            point = lonlat((c, r))
            if hit(point, lakes_):
                lakes.add((c, r))
            elif hit(point, boxes) and not hit(point, seas):
                land.add((c, r))
    return land, lakes


def _in_any(point, shapes):
    lon, lat = point
    return any(b[0] <= lon <= b[2] and b[1] <= lat <= b[3] and inside(point, p) for b, p in shapes)


def desert_at(point):
    return _in_any(point, _DESERT_BOXES)


def steppe_at(point):
    return _in_any(point, _STEPPE_BOXES)


def maghreb_at(point):
    """True on the land of North Africa north of the Sahara's heart (Morocco to Egypt, the Mediterranean shore)."""
    return _in_any(point, _MAGHREB_BOXES)


def marsh_at(point):
    """How marshy the region is (0..1): the Low Countries, the Pripet, river deltas, Florida."""
    lon, lat = point
    for x0, y0, x1, y1, k in MARSHES:
        if x0 <= lon <= x1 and y0 <= lat <= y1:
            return k
    return 0.0


