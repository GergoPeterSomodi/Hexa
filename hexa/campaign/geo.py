"""Real-world geography for the Age of Discovery campaign.

Coastlines are simplified (longitude, latitude) polygons, rasterised onto the hex grid with a
Mercator projection. Everything here is plain data plus a few geometry helpers.
"""
import math

# ----- projection -----------------------------------------------------------------
LON0, LON1 = -100.0, 46.5
LAT_TOP, LAT_BOTTOM = 62.5, -13.0
SCALE = 2                            # hexes per old hex width: the map is this many times finer
COL_DEG = 1.45 / SCALE               # degrees of longitude per hex
ROW_DEG = COL_DEG * 0.8660254        # Mercator degrees per row (hex rows are 0.866 hex widths apart)


def merc(lat):
    return math.degrees(math.log(math.tan(math.pi / 4 + math.radians(lat) / 2)))


def inv_merc(y):
    return math.degrees(2 * math.atan(math.exp(math.radians(y))) - math.pi / 2)


Y_TOP = merc(LAT_TOP)
COLS = int(math.ceil((LON1 - LON0) / COL_DEG))
ROWS = int(math.ceil((Y_TOP - merc(LAT_BOTTOM)) / ROW_DEG))


def lonlat(pos):
    col, row = pos
    lon = LON0 + (col + 0.5 * (row & 1) + 0.5) * COL_DEG
    lat = inv_merc(Y_TOP - (row + 0.5) * ROW_DEG)
    return lon, lat


def hex_of(lon, lat):
    row = int(round((Y_TOP - merc(lat)) / ROW_DEG - 0.5))
    col = int(round((lon - LON0) / COL_DEG - 0.5 - 0.5 * (row & 1)))
    return col, row


def inside(point, poly):
    x, y = point
    hit = False
    j = len(poly) - 1
    for i in range(len(poly)):
        xi, yi = poly[i]
        xj, yj = poly[j]
        if (yi > y) != (yj > y) and x < (xj - xi) * (y - yi) / (yj - yi) + xi:
            hit = not hit
        j = i
    return hit


def bbox(poly):
    xs, ys = [p[0] for p in poly], [p[1] for p in poly]
    return min(xs), min(ys), max(xs), max(ys)


def seg_distance(p, a, b):
    """Distance in degrees (longitude scaled by latitude) from p to segment ab."""
    k = math.cos(math.radians(p[1]))
    px, py = p[0] * k, p[1]
    ax, ay, bx, by = a[0] * k, a[1], b[0] * k, b[1]
    dx, dy = bx - ax, by - ay
    t = 0 if dx == dy == 0 else max(0, min(1, ((px - ax) * dx + (py - ay) * dy) / (dx * dx + dy * dy)))
    return math.hypot(px - ax - t * dx, py - ay - t * dy)


def line_distance(p, line):
    return min(seg_distance(p, line[i], line[i + 1]) for i in range(len(line) - 1))


